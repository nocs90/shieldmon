type resultJSON struct {
	Target       string         `json:"target,omitempty"`
	Platform     string         `json:"platform,omitempty"`
	Digest       string         `json:"digest"`
	DigestChange bool           `json:"digest_changed"`
	PrevDigest   string         `json:"previous_digest,omitempty"`
	SBOMsCreated []string       `json:"sboms_created,omitempty"`
	ScanID       int64          `json:"scan_id"`
	Kind         string         `json:"kind"`
	Status       string         `json:"status"`
	Tools        []model.Tool   `json:"tools"`
	Matches      int            `json:"matches"`
	Created      int            `json:"findings_created"`
	Carried      int            `json:"findings_carried_over"`
	Transitions  map[string]int `json:"transitions,omitempty"`
	Errors       []string       `json:"errors,omitempty"`
}

func toResultJSON(results []engine.Result) []resultJSON {
	list := make([]resultJSON, 0, len(results))
	for _, r := range results {
		tr := map[string]int{}
		for k, v := range r.Transitions {
			tr[string(k)] = v
		}
		list = append(list, resultJSON{
			Target: r.Target.Ref, Platform: r.Target.Platform, Digest: r.Resolved.Digest,
			DigestChange: r.DigestChange, PrevDigest: r.PrevDigest, SBOMsCreated: r.SBOMsCreated,
			ScanID: r.ScanID, Kind: r.Kind, Status: r.Status, Tools: r.Tools, Matches: r.Matches,
			Created: r.Created, Carried: r.Carried, Transitions: tr, Errors: r.Errors,
		})
	}
	return list
}

func printResults(w io.Writer, results []engine.Result, format string) error {
	if format == "json" {
		enc := json.NewEncoder(w)
		enc.SetIndent("", "  ")
		return enc.Encode(toResultJSON(results))
	}
	if format != "text" {
		return fmt.Errorf("unknown output format %q", format)
	}
	for _, r := range results {
		name := r.Target.Ref
		if name == "" {
			name = r.Resolved.Digest
		}
		fmt.Fprintf(w, "%s\n  digest   %s\n", name, r.Resolved.Digest)
		if r.DigestChange {
			fmt.Fprintf(w, "  changed  from %s\n", r.PrevDigest)
		}
		if len(r.SBOMsCreated) > 0 {
			fmt.Fprintf(w, "  sboms    generated by %s\n", strings.Join(r.SBOMsCreated, ", "))
		}
		var tools []string
		for _, t := range r.Tools {
			s := t.Name + " " + t.Version
			if !t.DBBuilt.IsZero() {
				s += " (DB " + t.DBBuilt.Format(time.DateOnly) + ")"
			}
			tools = append(tools, printable(s))
		}
		fmt.Fprintf(w, "  scan     #%d %s, %s — %s\n", r.ScanID, r.Kind, r.Status, strings.Join(tools, ", "))
		fmt.Fprintf(w, "  matches  %d (%d new findings", r.Matches, r.Created)
		if r.Carried > 0 {
			fmt.Fprintf(w, ", %d carried over from the previous digest", r.Carried)
		}
		fmt.Fprint(w, ")")
		for _, st := range model.AllStates {
			if n := r.Transitions[st]; n > 0 {
				fmt.Fprintf(w, ", %d → %s", n, st)
			}
		}
		fmt.Fprintln(w)
		for _, e := range r.Errors {
			fmt.Fprintf(w, "  error    %s\n", printable(e))
		}
	}
	return nil
}

