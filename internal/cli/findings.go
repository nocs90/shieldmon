func (a *app) reportCmd() *cobra.Command {
	cmd := &cobra.Command{Use: "report", Short: "Generate lifecycle reports"}
	var month, format, out string
	monthly := &cobra.Command{
		Use:   "monthly",
		Short: "Monthly lifecycle report: opened, fixed, MTTR, burndown, SLA breaches, accepted risks",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if err := a.setup(cmd); err != nil {
				return err
			}
			now := time.Now().UTC()
			ref := now
			if month != "" {
				t, err := time.Parse("2006-01", month)
				if err != nil {
					return fmt.Errorf("--month: want YYYY-MM: %w", err)
				}
				ref = t
			}
			sla, err := config.SLAProfile(a.cfg.SLA.Profile, a.cfg.SLA.Days)
			if err != nil {
				return err
			}
			r, err := report.BuildMonthly(cmd.Context(), a.store, report.MonthPeriod(ref), a.cfg.SLA.Profile, sla, now)
			if err != nil {
				return err
			}
			w := cmd.OutOrStdout()
			if out != "" {
				if err := os.MkdirAll(filepath.Dir(out), 0o750); err != nil {
					return err
				}
				// Reports are an inventory of weaknesses: owner-only.
				f, err := os.OpenFile(out, os.O_CREATE|os.O_WRONLY|os.O_TRUNC, 0o600)
				if err != nil {
					return err
				}
				defer f.Close()
				w = f
			}
			return report.Render(w, r, format)
		},
	}
	monthly.Flags().StringVar(&month, "month", "", "month YYYY-MM (default: current month)")
	monthly.Flags().StringVarP(&format, "output", "o", "md", "format: md, json, csv")
	monthly.Flags().StringVar(&out, "out", "", "write to file instead of stdout")
	cmd.AddCommand(monthly)
	return cmd
}

