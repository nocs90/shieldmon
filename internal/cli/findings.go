func (a *app) findingsCmd() *cobra.Command {
	cmd := &cobra.Command{Use: "findings", Short: "Query and triage findings"}

	var states []string
	var all bool
	var severity, digest, vuln, format, target string
	var limit int
	list := &cobra.Command{
		Use:   "list",
		Short: "List findings (default: active ones)",
		Args:  cobra.NoArgs,
		RunE: func(cmd *cobra.Command, _ []string) error {
			if err := a.setup(cmd); err != nil {
				return err
			}
			flt := store.FindingFilter{VulnID: vuln, Limit: limit}
			for _, arg := range []string{digest, target} {
				if arg == "" {
					continue
				}
				d, err := a.resolveDigest(cmd.Context(), arg)
				if err != nil {
					return err
				}
				flt.Digest = d
			}
			if severity != "" {
				if flt.MinSeverity = model.ParseSeverity(severity); flt.MinSeverity == model.SeverityUnknown {
					return fmt.Errorf("--severity: unknown severity %q", severity)
				}
			}
			switch {
			case len(states) > 0:
				for _, s := range states {
					st, err := model.ParseState(s)
					if err != nil {
						return err
					}
					flt.States = append(flt.States, st)
				}
			case !all:
				flt.States = []model.State{model.StateOpen, model.StateReopened, model.StateTriaged, model.StateInRemediation}
			}
			fs, err := a.store.ListFindings(cmd.Context(), flt)
			if err != nil {
				return err
			}
			policy, err := a.cfg.Policy()
			if err != nil {
				return err
			}
			return printFindings(cmd.OutOrStdout(), fs, format, policy)
		},
	}
	list.Flags().StringSliceVar(&states, "state", nil, "filter by state (repeatable)")
	list.Flags().BoolVar(&all, "all", false, "include every state")
	list.Flags().StringVar(&severity, "severity", "", "minimum severity: low, medium, high, critical")
	list.Flags().StringVar(&digest, "digest", "", "filter by image digest (a unique prefix is enough)")
	list.Flags().StringVar(&target, "target", "", "filter by target ID or image reference (its current digest)")
	list.Flags().StringVar(&vuln, "vuln", "", "filter by vulnerability ID or alias")
	list.Flags().IntVar(&limit, "limit", 0, "maximum rows")
	list.Flags().StringVarP(&format, "output", "o", "table", "output format: table, json, csv")

	show := &cobra.Command{
		Use:   "show ID",
		Short: "Show a finding with its full audit trail",
		Args:  cobra.ExactArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if err := a.setup(cmd); err != nil {
				return err
			}
			id, err := strconv.ParseInt(args[0], 10, 64)
			if err != nil {
				return fmt.Errorf("invalid finding ID %q", args[0])
			}
			ctx := cmd.Context()
			f, err := a.store.GetFinding(ctx, id)
			if err != nil {
				return err
			}
			evs, err := a.store.Events(ctx, id)
			if err != nil {
				return err
			}
			ds, err := a.store.Decisions(ctx, id)
			if err != nil {
				return err
			}
			w := cmd.OutOrStdout()
			fmt.Fprintf(w, "Finding #%d  %s  [%s]\n", f.ID, printable(f.VulnID), f.State)
			if len(f.Aliases) > 0 {
				fmt.Fprintf(w, "  aliases        %s\n", printable(strings.Join(f.Aliases, ", ")))
			}
			if f.Title != "" {
				fmt.Fprintf(w, "  title          %s\n", printable(f.Title))
			}
			fmt.Fprintf(w, "  severity       %s (CVSS %.1f %s)\n", f.Severity, f.CVSSScore, printable(f.CVSSVector))
			if f.EPSS > 0 || f.KEV {
				fmt.Fprintf(w, "  exploitation   EPSS %.3f, KEV %t\n", f.EPSS, f.KEV)
			}
			fmt.Fprintf(w, "  package        %s %s (%s)\n  purl           %s\n",
				printable(f.PkgName), printable(f.PkgVersion), printable(f.PkgType), printable(f.PURL))
			fmt.Fprintf(w, "  fix            %s\n", printable(fixLabel(f)))
			if policy, err := a.cfg.Policy(); err == nil {
				if d := slaDue(policy, f); !d.IsZero() {
					fmt.Fprintf(w, "  sla due        %s (%s, %s: %d days)\n", d.Format(time.DateOnly), policy.Profile, f.Severity, policy.SLADays[f.Severity])
				}
			}
			fmt.Fprintf(w, "  digest         %s\n  targets        %s\n", f.Digest, orDash(strings.Join(f.Targets, ", ")))
			fmt.Fprintf(w, "  scanners       %s\n", strings.Join(f.Scanners, ", "))
			fmt.Fprintf(w, "  first detected %s (age %d days)\n  last seen      %s\n", fmtTime(f.FirstDetected),
				int(time.Since(f.FirstDetected).Hours()/24), fmtTime(f.LastSeen))
			if f.PredecessorID != 0 {
				fmt.Fprintf(w, "  predecessor    #%d\n", f.PredecessorID)
			}
			if len(ds) > 0 {
				fmt.Fprintln(w, "\nDecisions:")
				for _, d := range ds {
					exp := "no expiry"
					if !d.ExpiresAt.IsZero() {
						exp = "expires " + d.ExpiresAt.Format(time.DateOnly)
					}
					kind := string(d.State)
					if d.Deviation != "" {
						kind += " (" + d.Deviation + ")"
					}
					fmt.Fprintf(w, "  #%d %s by %s on %s, %s: %s\n", d.ID, kind, printable(d.Author), d.CreatedAt.Format(time.DateOnly), exp, printable(d.Justification))
				}
			}
			fmt.Fprintln(w, "\nAudit trail:")
			for _, e := range evs {
				from := string(e.From)
				if from == "" {
					from = "∅"
				}
				ev := ""
				if e.ScanID != 0 {
					ev = fmt.Sprintf(" (evidence: scan #%d)", e.ScanID)
				}
				fmt.Fprintf(w, "  %s  %s → %s  by %s: %s%s\n", fmtTime(e.At), from, e.To, printable(e.Actor), printable(e.Reason), ev)
			}
			return nil
		},
	}

	cmd.AddCommand(list, show,
		a.transitionCmd("triage", model.StateTriaged, "Mark findings as triaged"),
		a.transitionCmd("remediate", model.StateInRemediation, "Mark findings as in remediation"),
		a.transitionCmd("untriage", model.StateOpen, "Move triaged findings back to open"),
		a.decisionCmd("accept-risk", model.StateRiskAccepted, "Accept the risk of findings until an expiry date"),
		a.decisionCmd("not-affected", model.StateNotAffected, "Declare findings not affected (VEX not_affected)"),
	)
	return cmd
}

func parseIDs(args []string) ([]int64, error) {
	ids := make([]int64, 0, len(args))
	for _, a := range args {
		id, err := strconv.ParseInt(a, 10, 64)
		if err != nil || id <= 0 {
			return nil, fmt.Errorf("invalid finding ID %q", a)
		}
		ids = append(ids, id)
	}
	return ids, nil
}

func (a *app) transitionCmd(use string, to model.State, short string) *cobra.Command {
	var note, actor string
	cmd := &cobra.Command{
		Use:   use + " ID...",
		Short: short,
		Args:  cobra.MinimumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if err := a.setup(cmd); err != nil {
				return err
			}
			ids, err := parseIDs(args)
			if err != nil {
				return err
			}
			if actor == "" {
				actor = engine.ActorFromEnv()
			}
			for _, id := range ids {
				if err := a.store.Transition(cmd.Context(), id, to, actor, note, time.Now()); err != nil {
					return fmt.Errorf("finding #%d: %w", id, err)
				}
				fmt.Fprintf(cmd.OutOrStdout(), "finding #%d → %s\n", id, to)
			}
			return nil
		},
	}
	cmd.Flags().StringVar(&note, "note", "", "reason recorded in the audit trail")
	cmd.Flags().StringVar(&actor, "actor", "", "who is acting (default $SHIELDMON_ACTOR or $USER)")
	return cmd
}

func (a *app) decisionCmd(use string, st model.State, short string) *cobra.Command {
	var justification, author, expires, deviation string
	cmd := &cobra.Command{
		Use:   use + " ID...",
		Short: short,
		Args:  cobra.MinimumNArgs(1),
		RunE: func(cmd *cobra.Command, args []string) error {
			if err := a.setup(cmd); err != nil {
				return err
			}
			ids, err := parseIDs(args)
			if err != nil {
				return err
			}
			dev, err := lifecycle.ParseDeviation(deviation)
			if err != nil {
				return err
			}
			policy, err := a.cfg.Policy()
			if err != nil {
				return err
			}
			d := lifecycle.Decision{State: st, Deviation: dev, Justification: justification, Author: author}
			if expires != "" {
				t, err := time.Parse(time.DateOnly, expires)
				if err != nil {
					return fmt.Errorf("--expires: want YYYY-MM-DD: %w", err)
				}
				d.ExpiresAt = t.UTC()
			}
			for _, id := range ids {
				applied, err := a.store.ApplyDecision(cmd.Context(), id, d, policy, time.Now())
				if err != nil {
					return fmt.Errorf("finding #%d: %w", id, err)
				}
				exp := "no expiry"
				if !applied.ExpiresAt.IsZero() {
					exp = "expires " + applied.ExpiresAt.Format(time.DateOnly)
				}
				label := string(st)
				if applied.Deviation != lifecycle.DeviationNone {
					label += " (" + string(applied.Deviation) + ")"
				}
				fmt.Fprintf(cmd.OutOrStdout(), "finding #%d → %s, %s\n", id, label, exp)
			}
			return nil
		},
	}
	cmd.Flags().StringVar(&justification, "justification", "", "why (required; for not-affected use a VEX justification, e.g. vulnerable_code_not_in_execute_path)")
	cmd.Flags().StringVar(&author, "author", "", "accountable person (required)")
	if st == model.StateRiskAccepted {
		cmd.Long = `Accept the risk of findings until an expiry date, under the remediation policy
(sla.profile, default standard: critical/high 30, medium 90, low 180 days
from first detection; adjustable with sla.days).

  • Without --deviation the acceptance cannot outlive the remediation deadline;
    --expires defaults to that deadline.
  • --deviation vendor-dependency: no vendor fix exists ("won't fix" or not fixed
    yet). Allowed only when no fixed version is known; expires within
    decisions.vendor_dependency_max_days (default 30, renewable) and reopens
    automatically as soon as a fix is published.
  • --deviation operational-requirement: a fix exists but cannot be applied.
    Needs a detailed justification and an explicit --expires (max 365 days).`
		cmd.Example = `  shieldmon findings accept-risk 42 --author alice --justification "no network listener; RISK-12"
  shieldmon findings accept-risk 57 --deviation vendor-dependency --author alice \
    --justification "Red Hat: will not fix (low impact on UBI); tracked monthly"`
		cmd.Flags().StringVar(&deviation, "deviation", "", "vendor-dependency | operational-requirement (to go beyond the SLA deadline)")
	}
	cmd.Flags().StringVar(&expires, "expires", "", "expiry date YYYY-MM-DD (default: from the remediation policy)")
	_ = cmd.MarkFlagRequired("justification")
	_ = cmd.MarkFlagRequired("author")
	return cmd
}

// fixLabel shows fixed versions, or the vendor status when there are none.
func fixLabel(f store.Finding) string {
	if len(f.FixVersions) > 0 {
		return strings.Join(f.FixVersions, ",")
	}
	switch f.FixState {
	case model.FixWontFix:
		return "won't fix"
	case model.FixNotFixed:
		return "no fix yet"
	}
	return "-"
}

func slaDue(p lifecycle.Policy, f store.Finding) time.Time {
	return p.SLADue(lifecycle.Subject{Severity: f.Severity, FirstDetected: f.FirstDetected})
}

func printFindings(w io.Writer, fs []store.Finding, format string, policy lifecycle.Policy) error {
	switch format {
	case "json":
		type row struct {
			store.Finding
			Severity string `json:"severity"`
		}
		rows := make([]row, 0, len(fs))
		for _, f := range fs {
			rows = append(rows, row{Finding: f, Severity: f.Severity.String()})
		}
		enc := json.NewEncoder(w)
		enc.SetIndent("", "  ")
		return enc.Encode(rows)
	case "csv":
		cw := csv.NewWriter(w)
		_ = cw.Write([]string{"id", "severity", "vuln_id", "package", "version", "fix_versions", "fix_state", "state", "first_detected", "sla_due", "targets", "digest", "purl"})
		for _, f := range fs {
			due := ""
			if d := slaDue(policy, f); !d.IsZero() {
				due = d.Format(time.DateOnly)
			}
			rec := []string{
				strconv.FormatInt(f.ID, 10), f.Severity.String(), f.VulnID, f.PkgName, f.PkgVersion,
				strings.Join(f.FixVersions, " "), string(f.FixState), string(f.State), f.FirstDetected.Format(time.RFC3339), due,
				strings.Join(f.Targets, "; "), f.Digest, f.PURL,
			}
			for i, v := range rec {
				rec[i] = report.CSVSafe(v)
			}
			_ = cw.Write(rec)
		}
		cw.Flush()
		return cw.Error()
	case "table":
		tw := tabwriter.NewWriter(w, 0, 4, 2, ' ', 0)
		fmt.Fprintln(tw, "ID\tSEVERITY\tVULNERABILITY\tPACKAGE\tVERSION\tFIX\tSTATE\tAGE\tSLA DUE\tTARGET")
		for _, f := range fs {
			vuln := printable(f.VulnID)
			if f.KEV {
				vuln += " [KEV]"
			}
			target := strings.Join(f.Targets, ", ")
			if target == "" {
				target = shortDigest(f.Digest)
			}
			due := "-"
			if d := slaDue(policy, f); !d.IsZero() {
				due = d.Format(time.DateOnly)
				if time.Now().After(d) && f.State.Active() {
					due += " ⚠"
				}
			}
			fmt.Fprintf(tw, "%d\t%s\t%s\t%s\t%s\t%s\t%s\t%dd\t%s\t%s\n", f.ID, f.Severity, vuln, short(printable(f.PkgName), 30),
				short(printable(f.PkgVersion), 24), short(printable(fixLabel(f)), 24), f.State,
				int(time.Since(f.FirstDetected).Hours()/24), due, target)
		}
		if err := tw.Flush(); err != nil {
			return err
		}
		fmt.Fprintf(w, "%d finding(s)\n", len(fs))
		return nil
	}
	return fmt.Errorf("unknown output format %q", format)
}

